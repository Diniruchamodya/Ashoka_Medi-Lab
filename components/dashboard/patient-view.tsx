'use client'

import { Bell, CalendarDays, CalendarPlus, Download, FileText, LayoutDashboard, Lock, TestTube, UserRound } from 'lucide-react'
import { useState } from 'react'
import { Button } from '@/components/ui/button'
import { useDemoStore } from '@/components/demo/demo-store'
import { BookingForm } from '@/components/booking/booking-form'
import { DashboardShell } from '@/components/dashboard/shell'
import { Panel, StatCard, Table, WorkflowStepper, formatDateTime } from '@/components/dashboard/widgets'
import { DemoNotice, EmptyState, Field, Input, Select, StatusBadge } from '@/components/shared/ui'
import { useToast } from '@/components/shared/toast'
import type { Patient, TestOrder } from '@/lib/demo-data'

function usePatient() {
  const s = useDemoStore()
  const patient = s.patients.find((p) => p.id === s.session!.userId)!
  return {
    ...s,
    patient,
    myAppts: s.appointments.filter((a) => a.patientId === patient.id),
    myOrders: s.orders.filter((o) => o.patientId === patient.id),
    myNotes: s.notifications.filter((n) => n.patientId === patient.id),
  }
}

const escape = (v: string) => v.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!)

function downloadReport(order: TestOrder, patient: Patient, serviceName: (id: string) => string, branchName: (id: string) => string) {
  const rows = order.results.map((r) => `<tr><td>${escape(serviceName(r.testId))}</td><td>${escape(r.value)} ${escape(r.unit)}</td><td>${escape(r.reference)}</td><td>${r.flag ?? ''}</td></tr>`).join('')
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${order.id} report</title><style>body{font-family:system-ui,sans-serif;max-width:760px;margin:40px auto;color:#0f2740}h1{color:#0891b2}table{width:100%;border-collapse:collapse;margin-top:16px}td,th{border-bottom:1px solid #ddd;padding:8px;text-align:left}.demo{background:#fff4d6;border:1px solid #f5c451;padding:10px;border-radius:8px;font-weight:600}</style></head><body><p class="demo">DEMO REPORT — NOT A REAL MEDICAL REPORT. Generated by a prototype using sample data.</p><h1>Ashoka Medi-Lab</h1><p><b>Patient:</b> ${escape(patient.name)} &nbsp; <b>DOB:</b> ${patient.dob} &nbsp; <b>Gender:</b> ${patient.gender}</p><p><b>Order:</b> ${order.id} &nbsp; <b>Sample:</b> ${order.sampleId ?? ''} &nbsp; <b>Laboratory:</b> ${escape(branchName(order.processingBranchId))}</p><table><thead><tr><th>Test</th><th>Result</th><th>Reference</th><th>Flag</th></tr></thead><tbody>${rows}</tbody></table><p style="margin-top:24px"><b>Approved by:</b> ${escape(order.approver ?? '')}</p></body></html>`
  const url = URL.createObjectURL(new Blob([html], { type: 'text/html' }))
  const a = document.createElement('a')
  a.href = url
  a.download = `ashoka-demo-report-${order.id}.html`
  a.click()
  URL.revokeObjectURL(url)
}

function Overview({ go }: { go: (id: string) => void }) {
  const { patient, myAppts, myOrders } = usePatient()
  const upcoming = myAppts.filter((a) => a.status === 'Booked')
  return (
    <div className="space-y-6">
      <div className="rounded-2xl bg-gradient-to-br from-primary to-[oklch(0.45_0.1_235)] p-6 text-primary-foreground">
        <p className="text-sm text-primary-foreground/80">Welcome back</p>
        <p className="mt-1 text-2xl font-bold">{patient.name}</p>
        <Button onClick={() => go('book')} variant="secondary" className="mt-4 rounded-full"><CalendarPlus className="size-4" aria-hidden /> Book a test</Button>
      </div>
      <div className="grid gap-4 sm:grid-cols-3">
        <StatCard icon={CalendarDays} label="Upcoming appointments" value={upcoming.length} />
        <StatCard icon={TestTube} label="Tests in progress" value={myOrders.filter((o) => o.status !== 'Released').length} tone="warning" />
        <StatCard icon={FileText} label="Reports available" value={myOrders.filter((o) => o.status === 'Released').length} tone="success" />
      </div>
      <Tracking />
    </div>
  )
}

function Tracking() {
  const { myOrders, serviceName } = usePatient()
  if (myOrders.length === 0) return <EmptyState title="No tests yet" description="Your test progress will appear here once a sample is ordered." />
  return (
    <Panel title="Test progress">
      <div className="space-y-6">
        {myOrders.map((o) => (
          <div key={o.id} className="border-b pb-6 last:border-0 last:pb-0">
            <div className="mb-4 flex flex-wrap items-center justify-between gap-2">
              <p className="font-semibold">{o.testIds.map(serviceName).join(', ')}<span className="ml-2 font-mono text-xs font-normal text-muted-foreground">{o.id}</span></p>
              <StatusBadge status={o.status === 'Correction Requested' || o.status === 'Result Entered' || o.status === 'Approved' ? 'Under review' : o.status} />
            </div>
            <WorkflowStepper status={o.status} transfer={o.branchId !== o.processingBranchId} />
          </div>
        ))}
      </div>
    </Panel>
  )
}

function Reports() {
  const { myOrders, patient, serviceName, branchName, log } = usePatient()
  const toast = useToast()
  return (
    <Panel title="My reports">
      <DemoNotice className="mb-4">Only reports approved and released by an authorised professional are available to download.</DemoNotice>
      <Table head={['Order', 'Tests', 'Updated', 'Status', '']} empty={myOrders.length === 0}>
        {myOrders.map((o) => (
          <tr key={o.id}>
            <td className="font-mono text-xs font-semibold">{o.id}</td>
            <td className="max-w-56">{o.testIds.map(serviceName).join(', ')}</td>
            <td className="whitespace-nowrap text-muted-foreground">{formatDateTime(o.updatedAt)}</td>
            <td><StatusBadge status={o.status === 'Released' ? 'Released' : 'Pending'} /></td>
            <td className="text-right">
              {o.status === 'Released' ? (
                <Button size="sm" onClick={() => { downloadReport(o, patient, serviceName, branchName); log(patient.name, `Downloaded report ${o.id}`); toast({ tone: 'success', title: 'Demo report downloaded' }) }}>
                  <Download className="size-3.5" aria-hidden /> Download
                </Button>
              ) : (
                <span className="inline-flex items-center gap-1 text-xs text-muted-foreground"><Lock className="size-3.5" aria-hidden /> Awaiting approval</span>
              )}
            </td>
          </tr>
        ))}
      </Table>
    </Panel>
  )
}

function Appointments() {
  const { myAppts, branchName } = usePatient()
  return (
    <Panel title="Appointment history">
      <Table head={['ID', 'Branch', 'Date & time', 'Status']} empty={myAppts.length === 0}>
        {myAppts.map((a) => (
          <tr key={a.id}>
            <td className="font-mono text-xs font-semibold">{a.id}</td>
            <td>{branchName(a.branchId)}</td>
            <td>{a.date} · {a.time}</td>
            <td><StatusBadge status={a.status} /></td>
          </tr>
        ))}
      </Table>
    </Panel>
  )
}

function Profile() {
  const { patient, dispatch, log } = usePatient()
  const toast = useToast()
  const [f, setF] = useState(patient)
  const [error, setError] = useState('')
  return (
    <Panel title="My profile" className="max-w-2xl">
      <form
        noValidate
        className="space-y-4"
        onSubmit={(e) => {
          e.preventDefault()
          if (f.name.trim().length < 2) return setError('Enter your full name.')
          if (!/^[+\d][\d\s-]{8,15}$/.test(f.phone.trim())) return setError('Enter a valid phone number.')
          if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(f.email)) return setError('Enter a valid email.')
          setError('')
          dispatch({ type: 'updatePatient', patient: f })
          log(f.name, 'Updated profile')
          toast({ tone: 'success', title: 'Profile updated' })
        }}
      >
        {error && <p role="alert" className="text-sm text-destructive">{error}</p>}
        <Field label="Full name">{(id) => <Input id={id} value={f.name} onChange={(e) => setF({ ...f, name: e.target.value })} autoComplete="name" />}</Field>
        <div className="grid gap-4 sm:grid-cols-2">
          <Field label="Phone">{(id) => <Input id={id} type="tel" value={f.phone} onChange={(e) => setF({ ...f, phone: e.target.value })} autoComplete="tel" />}</Field>
          <Field label="Email">{(id) => <Input id={id} type="email" value={f.email} onChange={(e) => setF({ ...f, email: e.target.value })} autoComplete="email" />}</Field>
          <Field label="Date of birth">{(id) => <Input id={id} type="date" value={f.dob} onChange={(e) => setF({ ...f, dob: e.target.value })} />}</Field>
          <Field label="Gender">{(id) => <Select id={id} value={f.gender} onChange={(e) => setF({ ...f, gender: e.target.value as Patient['gender'] })}><option>Female</option><option>Male</option><option>Other</option></Select>}</Field>
        </div>
        <Button type="submit">Save changes</Button>
      </form>
    </Panel>
  )
}

function Notifications() {
  const { myNotes, patient, dispatch } = usePatient()
  return (
    <Panel title="Notifications" action={myNotes.some((n) => !n.read) && <Button size="sm" variant="outline" onClick={() => dispatch({ type: 'readNotifications', patientId: patient.id })}>Mark all read</Button>}>
      {myNotes.length === 0 ? (
        <EmptyState title="No notifications" />
      ) : (
        <ul className="space-y-2">
          {myNotes.map((n) => (
            <li key={n.id} className="flex items-start gap-3 rounded-xl border p-4">
              <Bell className={n.read ? 'mt-0.5 size-4 text-muted-foreground' : 'mt-0.5 size-4 text-primary'} aria-hidden />
              <div className="flex-1">
                <p className={n.read ? 'text-sm text-muted-foreground' : 'text-sm font-medium'}>{n.message}</p>
                <p className="mt-1 text-xs text-muted-foreground">{formatDateTime(n.at)}</p>
              </div>
              {!n.read && <span className="mt-1.5 size-2 rounded-full bg-primary" aria-label="Unread" />}
            </li>
          ))}
        </ul>
      )}
    </Panel>
  )
}

function Book() {
  const { patient } = usePatient()
  return <BookingForm patient={patient} />
}

export function PatientView() {
  const { session, notifications } = useDemoStore()
  return (
    <DashboardShell
      role="patient"
      sections={[
        { id: 'overview', label: 'Overview', icon: LayoutDashboard, render: (go) => <Overview go={go} /> },
        { id: 'book', label: 'Book a test', icon: CalendarPlus, render: () => <Book /> },
        { id: 'appointments', label: 'Appointments', icon: CalendarDays, render: () => <Appointments /> },
        { id: 'tracking', label: 'Test tracking', icon: TestTube, render: () => <Tracking /> },
        { id: 'reports', label: 'Reports', icon: FileText, render: () => <Reports /> },
        { id: 'notifications', label: 'Notifications', icon: Bell, render: () => <Notifications />, badge: notifications.filter((n) => n.patientId === session?.userId && !n.read).length },
        { id: 'profile', label: 'Profile', icon: UserRound, render: () => <Profile /> },
      ]}
    />
  )
}
